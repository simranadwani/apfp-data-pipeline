"""
Writes LineageData.js (repository root) from lineage_model.py + chart_passport.py + code_columns.json.
LineageData.js is read by Lineage.js (Data_Dictionary and Chart_Passport tabs). Re-run after changing either model file:
    python3 docs/lineage/export_catalog.py
tests/pipeline.test.js fails if the file is out of date or a final column / chart has no entry.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lineage_model as lm
import chart_passport as cp

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
CODE = json.load(open(os.path.join(HERE, 'code_columns.json'), encoding='utf-8'))
HOW = {'copy': 'Copied as entered', 'join': 'Looked up from another table', 'calc': 'Calculated', 'const': 'Fixed value',
       'run': 'Date of the run', 'blank': 'Empty on purpose'}


def source_of(ref, seen=None):
    """'table.column' -> set of 'Source tab > Source header' for a staging or final column."""
    table, col = ref.split('.', 1)
    if table.startswith('stg_'):
        st = CODE['staging'][table]
        hdr = next((x['source_header'] for x in st['columns'] if x['name'] == col), col)
        return {f"{st['source_tab']} > {hdr}"}
    out = set()
    for name, cat, ups, rule in lm.FINAL[table]:
        if name == col:
            for u in ups:
                out |= source_of(u)
    return out


def tabs_of(refs):
    return sorted({s.split(' > ')[0] for r in refs for s in source_of(r)})


used = {}
for cid, (table, shows, flt, cols) in cp.CHARTS.items():
    for col in cols:
        used.setdefault(col, []).append(cid)

columns = {}
for table, rows in lm.FINAL.items():
    for name, cat, ups, rule in rows:
        ref = f'{table}.{name}'
        srcs = set()
        for u in ups:
            srcs |= source_of(u)
        columns[ref] = {'meaning': rule, 'how': HOW[cat], 'source_tabs': sorted({s.split(' > ')[0] for s in srcs}),
                        'source_columns': sorted(srcs), 'charts': sorted(used.get(ref, []))}

charts = []
for cid, (table, shows, flt, cols) in cp.CHARTS.items():
    charts.append({'id': cid, 'page': cp.PAGES[cid[0]], 'name': lm.CHART_NAMES[cid], 'table': table, 'shows': shows, 'filter': flt,
                   'columns': [c.split('.', 1)[1] for c in cols], 'source_tabs': tabs_of(cols)})

tables = {t: {'name': lm.TABLE_INFO[t][0], 'about': lm.TABLE_INFO[t][1]} for t in lm.FINAL}
body = json.dumps({'tables': tables, 'columns': columns, 'charts': charts}, ensure_ascii=False, indent=1)
open(os.path.join(ROOT, 'LineageData.js'), 'w', encoding='utf-8').write(
    '/**\n * LineageData.js - GENERATED by docs/lineage/export_catalog.py from lineage_model.py and chart_passport.py.\n'
    ' * Do not edit by hand: change the model files and re-run the script. Read by Lineage.js.\n */\n\n'
    'const LINEAGE_DATA = ' + body + ';\n')
print(len(columns), 'columns,', len(charts), 'charts')
